
CREATE TABLE users
(
    id       INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email    VARCHAR(255)                         NOT NULL,
    password VARCHAR(255)                         NOT NULL,
    phone    VARCHAR(255),
    role     VARCHAR(255)                         NOT NULL,
    enabled  BOOLEAN                              NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uc_users_email UNIQUE (email)
);

CREATE TABLE credit_products
(
    id              INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title           VARCHAR(255),
    min_amount      BIGINT                               NOT NULL,
    max_amount      BIGINT                               NOT NULL,
    min_term_months INT                                  NOT NULL,
    max_term_months INT                                  NOT NULL,
    interest_rate   DOUBLE PRECISION                     NOT NULL,
    active          BOOLEAN                              NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP                            NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_credit_products PRIMARY KEY (id)
);

CREATE TABLE companies
(
    id            INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(255),
    inn           VARCHAR(255),
    ogrn          VARCHAR(255),
    legal_address VARCHAR(255),
    revenue       BIGINT,
    user_id       INT,
    CONSTRAINT pk_companies PRIMARY KEY (id),
    CONSTRAINT uc_companies_user UNIQUE (user_id),
    CONSTRAINT fk_companies_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE verifications
(
    id            INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    egrul_status  VARCHAR(255),
    bki_status    VARCHAR(255),
    final_verdict VARCHAR(255),
    issue_date    TIMESTAMP,
    reasons       VARCHAR(1000),
    CONSTRAINT pk_verifications PRIMARY KEY (id)
);

CREATE TABLE applications
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id        INT,
    verification_id   INT,
    credit_product_id INT,
    requested_amount  BIGINT,
    term_months       INT,
    status            VARCHAR(255),
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT fk_applications_on_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_applications_on_verification FOREIGN KEY (verification_id) REFERENCES verifications (id),
    CONSTRAINT fk_applications_on_credit_product FOREIGN KEY (credit_product_id) REFERENCES credit_products (id)
);