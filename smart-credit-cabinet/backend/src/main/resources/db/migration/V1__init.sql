-- Схема кредитного конвейера. SQL совместим с PostgreSQL и H2 (режим PostgreSQL) для тестов.
-- JSON-поля хранятся в text: снимки ответов источников, факторы скоринга, предложения.

create table companies (
    id            bigint generated by default as identity primary key,
    inn           varchar(12)  not null unique,
    name          varchar(255) not null,
    legal_form    varchar(8)   not null,
    ogrn          varchar(15),
    okved         varchar(16),
    director_name varchar(255),
    registered_at date
);

create table users (
    id            bigint generated by default as identity primary key,
    login         varchar(64)  not null unique,
    password_hash varchar(255) not null,
    role          varchar(16)  not null,
    full_name     varchar(255) not null,
    company_id    bigint references companies (id)
);

create table applications (
    id                        bigint generated by default as identity primary key,
    number                    varchar(32) unique,
    company_id                bigint      not null references companies (id),
    created_by                bigint      not null references users (id),
    product_code              varchar(32) not null,
    purpose                   varchar(32) not null,
    amount                    bigint      not null,
    term_months               int         not null,
    revenue_12m               bigint,
    existing_monthly_payments bigint      not null default 0,
    bki_consent_at            timestamp with time zone,
    status                    varchar(32) not null,
    assignee_id               bigint references users (id),
    created_at                timestamp with time zone not null,
    updated_at                timestamp with time zone not null,
    submitted_at              timestamp with time zone,
    decided_at                timestamp with time zone,
    version                   bigint      not null default 0
);
create index idx_applications_company on applications (company_id);
create index idx_applications_status on applications (status);

create table application_checks (
    id             bigint generated by default as identity primary key,
    application_id bigint      not null references applications (id) on delete cascade,
    step           varchar(32) not null,
    step_order     int         not null,
    status         varchar(16) not null,
    attempts       int         not null default 0,
    result         text,
    error          text,
    updated_at     timestamp with time zone not null,
    constraint uq_check_step unique (application_id, step)
);

create table application_events (
    id             bigint generated by default as identity primary key,
    application_id bigint      not null references applications (id) on delete cascade,
    event_type     varchar(32) not null,
    from_status    varchar(32),
    to_status      varchar(32),
    actor_type     varchar(16) not null,
    actor_id       bigint references users (id),
    message        text        not null,
    created_at     timestamp with time zone not null
);
create index idx_events_application on application_events (application_id);

create table decisions (
    id             bigint generated by default as identity primary key,
    application_id bigint      not null references applications (id) on delete cascade,
    source         varchar(16) not null,
    outcome        varchar(16) not null,
    score          int,
    grade          varchar(1),
    factors        text,
    stop_factors   text,
    reasons        text,
    proposal       text,
    note           text,
    decided_by     bigint references users (id),
    policy_version varchar(32),
    created_at     timestamp with time zone not null
);
create index idx_decisions_application on decisions (application_id);

create table offers (
    id                bigint generated by default as identity primary key,
    application_id    bigint           not null references applications (id) on delete cascade,
    decision_id       bigint           not null references decisions (id),
    kind              varchar(16)      not null,
    product_code      varchar(32)      not null,
    amount            bigint           not null,
    term_months       int              not null,
    rate              double precision not null,
    monthly_payment   bigint           not null,
    status            varchar(16)      not null,
    signing_code_hash varchar(128),
    created_at        timestamp with time zone not null,
    accepted_at       timestamp with time zone,
    signed_at         timestamp with time zone
);
create index idx_offers_application on offers (application_id);

create table info_requests (
    id                bigint generated by default as identity primary key,
    application_id    bigint      not null references applications (id) on delete cascade,
    requested_by      varchar(16) not null,
    requested_by_user bigint references users (id),
    return_status     varchar(32) not null,
    items             text        not null,
    note              text,
    status            varchar(16) not null,
    response          text,
    created_at        timestamp with time zone not null,
    answered_at       timestamp with time zone
);
create index idx_info_requests_application on info_requests (application_id);

create table documents (
    id              bigint generated by default as identity primary key,
    application_id  bigint       not null references applications (id) on delete cascade,
    info_request_id bigint references info_requests (id),
    doc_type        varchar(32)  not null,
    filename        varchar(255) not null,
    content_type    varchar(128) not null,
    size_bytes      bigint       not null,
    sha256          varchar(64)  not null,
    storage_path    varchar(512) not null,
    uploaded_by     bigint       not null references users (id),
    created_at      timestamp with time zone not null
);
create index idx_documents_application on documents (application_id);
